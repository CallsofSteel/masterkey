#!/usr/bin/env node
// Masterkey — build ONE provider's fan-out batch from the RICH funnel (bazaar+agentcash), correctly.
//
// Fixes the two bugs the 2026-07-30 audit found:
//   1. The old ad-hoc reader used `Object.values(funnel).find(Array.isArray)` which grabbed
//      `nameCollisions` (bare URL strings) instead of `batches` (the real 29k rich-record worklist).
//      This reads `funnel.batches`.
//   2. The funnel now carries bazaar `accepts` (→ price, no probe) + `bazaar` (input example / output
//      example / JSON schema) + `traction`. We pass those straight into the fan-out args as `callHint` +
//      `priceUsd`, so agents pay with the documented call and the pre-filter can skip the live probe.
//
// It writes NOTHING to the registry. Output: a fan-out args JSON under discovery/ + a summary to stdout.
//
// Usage:
//   node scripts/registry/next-provider-batch.mjs --host=<substr>         # one host
//   node scripts/registry/next-provider-batch.mjs --auto                  # highest-traction fresh host
//   node scripts/registry/next-provider-batch.mjs --auto --cap=0.25 --max=120
//
// The live 402 re-capture + pay-verify at INDEX time stays authoritative (§5.5C, staleness) — bazaar
// accepts here are for PRE-FILTER + callHint only; the agent still captures fresh accepts when it pays.

import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dir = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dir, "../..");
const DISCOVERY = join(ROOT, "data/registry/discovery");
const LEDGER = join(ROOT, "data/registry/indexing-progress.jsonl");
const CURATION = join(__dir, "curation");

const argv = process.argv.slice(2);
const arg = (k, d) => { const a = argv.find((x) => x.startsWith(`--${k}=`)); return a ? a.slice(k.length + 3) : d; };
const has = (k) => argv.includes(`--${k}`);
const HOST = arg("host", "");
const AUTO = has("auto");
const CAP = Number(arg("cap", "0.25"));
const MAX = Number(arg("max", "120"));       // safety cap on batch size (keep waves sane)
const readJson = (p) => { try { return JSON.parse(readFileSync(p, "utf8")); } catch { return null; } };
const bare = (u) => String(u || "").replace(/^https?:\/\//, "");
const norm = (u) => bare(u).replace(/\?.*$/, "").replace(/\/+$/, "").toLowerCase();  // strip query + trailing slash for match
const BYSUBCAT = join(ROOT, "data/registry/by-subcat");

if (!HOST && !AUTO) { console.error("pass --host=<substring> or --auto"); process.exit(1); }

// ── newest RICH funnel ──
const funnelFile = readdirSync(DISCOVERY).filter((f) => /^funnel-\d{6,}\.json$/.test(f)).sort().pop();  // timestamped only
if (!funnelFile) { console.error("no funnel-*.json"); process.exit(1); }
const funnel = readJson(join(DISCOVERY, funnelFile));
const records = [];
for (const b of funnel.batches || []) for (const e of b.endpoints || []) records.push(e);   // ← batches, NOT nameCollisions
if (!records.length) { console.error(`funnel ${funnelFile} has no batches[].endpoints`); process.exit(1); }

// ── ever-terminal ledger URLs (never re-offer something indexed/deferred/etc.) ──
const terminal = new Set();
if (existsSync(LEDGER)) for (const ln of readFileSync(LEDGER, "utf8").trim().split("\n")) {
  if (!ln) continue; try { const r = JSON.parse(ln); const st = r.status || r.state || ""; if (st && st !== "probed" && st !== "todo" && r.url) terminal.add(bare(r.url)); } catch { /* skip */ }
}

// ── already-SHIPPED backend/operation URLs (exclude anything already in the registry, incl. hidden) ──
// The ledger only tracks THIS campaign; services indexed in earlier (pre-ledger) efforts would otherwise
// be re-offered and waste agents re-deferring dupes. Read the generated by-subcat files (resolved inline
// backends) and exclude every URL already present, query-stripped.
const indexed = new Set();
if (existsSync(BYSUBCAT)) for (const f of readdirSync(BYSUBCAT).filter((x) => x.endsWith(".json"))) {
  const d = readJson(join(BYSUBCAT, f)); if (!d) continue;
  const arr = Array.isArray(d) ? d : (d.entries || d.services || []);
  for (const e of arr) {
    if (!e || typeof e !== "object") continue;
    for (const b of e.backends || []) if (b && typeof b === "object" && b.url) indexed.add(norm(b.url));
    for (const o of e.operations || []) if (o && typeof o === "object" && (o.url || o.path)) indexed.add(norm(o.url || o.path));
  }
}

// ── price from bazaar accepts (USDC atomic → USD); null if not USDC-priced ──
const USDC = new Set(["0x833589fcd6edb6e08f4c7c32d4f71b54bda02913", "0xa0b86991c6218b36c1d19d4a2e9eb0ce3606eb48", "epjfwdd5aufqssqem2qn1xzybapc8g4weggkzwytdt1v"]);
function priceOf(accepts) {
  let best = null;
  for (const a of accepts || []) {
    const v = a?.maxAmountRequired ?? a?.amount;
    if (v == null || !/^\d+$/.test(String(v))) continue;
    if (USDC.has(String(a.asset || "").toLowerCase()) || a?.extra?.name === "USD Coin") { const usd = Number(v) / 1e6; if (best == null || usd < best) best = usd; }
  }
  return best;
}
// A round-dollar bazaar amount ($1/$2/$3/$10/$20…) is often a worst-case ceiling for dynamic pricing —
// flag it so the agent re-quotes with a real body (qa-pay still enforces the cap).
const ceilingSuspect = (p) => p != null && p >= 1 && Number.isInteger(p);

// ── build candidate rows for the chosen host(s) ──
const tractionOf = (e) => (e.traction?.transactionCount ?? 0) + (e.traction?.volumeUsd ?? 0);
let pool = records.filter((e) => !terminal.has(bare(e.url)) && !indexed.has(norm(e.url)));
if (HOST) pool = pool.filter((e) => (e.host || "").includes(HOST));
if (AUTO && !HOST) {
  // pick the fresh host with the most total traction (real paid demand) — better than alphabetical
  const byHost = new Map();
  for (const e of pool) { const h = e.host; if (!byHost.has(h)) byHost.set(h, 0); byHost.set(h, byHost.get(h) + tractionOf(e)); }
  const top = [...byHost.entries()].sort((a, b) => b[1] - a[1])[0];
  if (!top) { console.error("no fresh endpoints left"); process.exit(1); }
  pool = pool.filter((e) => e.host === top[0]);
}
if (!pool.length) { console.error("no fresh endpoints for that host"); process.exit(1); }
const host = pool[0].host;

// ── classify: payable≤cap (agent set) vs over-cap (defer) vs unknown-price (agent probes live) ──
const payable = [], overCap = [], unknownPrice = [];
for (const e of pool) {
  const p = priceOf(e.accepts);
  const method = (e.bazaar?.info?.input?.method || e.method || "POST").toUpperCase();
  const inputExample = e.bazaar?.info?.input?.body || e.bazaar?.info?.input?.queryParams || e.bazaar?.info?.input?.pathParams || null;
  // Lean callHint (keep the args inline-able): method + documented example + a trimmed human summary.
  // The verbose JSON schema / output example are intentionally dropped from the fan-out args — the agent
  // re-reads the live 402 + provider docs anyway; the example is the high-value bit that avoids a paid 400.
  const rawSummary = (e.bazaar?.info?.summary || e.description || "").replace(/^Origin URL:[\s\S]*?Summary:\s*/, "").replace(/\s+/g, " ").trim();
  const callHint = { method, inputExample: inputExample || null, summary: rawSummary.slice(0, 160) };
  const row = { url: e.url, host, method, priceUsd: p, ceilingSuspect: ceilingSuspect(p), callHint,
    hasBazaar: !!e.bazaar, accepts: e.accepts || null, traction: tractionOf(e) || 0 };
  if (p == null) unknownPrice.push(row);                 // bazaar has no USDC price → agent probes live
  else if (p > CAP && !ceilingSuspect(p)) overCap.push(row);  // firm over-cap → defer
  else payable.push(row);                                // ≤cap or ceiling-suspect → agent set
}
// prioritise the agent set by traction; cap at MAX
payable.sort((a, b) => b.traction - a.traction);
unknownPrice.sort((a, b) => b.traction - a.traction);
const agentSet = [...payable, ...unknownPrice].slice(0, MAX);

const brand = host.replace(/^(api|x402|www|data|proxy|gateway|app|mcp|edge)\./, "").split(".")[0].replace(/(^|[-_])(\w)/g, (m, s, c) => (s ? " " : "") + c.toUpperCase()).trim();
const args = {
  label: host.replace(/[^a-z0-9]+/gi, "-"),
  providerContext: { host, brand, note: `Provider ${brand} (host ${host}). Endpoints carry a callHint from the x402 bazaar (documented method + input example + output example + schema when present) — PREFER it; pay with the given example. bazaar accepts are a hint — CAPTURE fresh accepts from the live 402 at index time (§5.5C). Each op = its own service "${brand} <Operation>"; consult the index for merges/folds/aliases; classify into an existing subcategory.`, existing: [] },
  endpoints: agentSet.map(({ traction, accepts, hasBazaar, ...e }) => e),
};
const outFile = join(DISCOVERY, `nextbatch-${args.label}.json`);
writeFileSync(outFile, JSON.stringify(args, null, 1));

console.log(`funnel : ${funnelFile}`);
console.log(`host   : ${host}  (brand "${brand}")`);
console.log(`pool   : ${pool.length} fresh (not terminal in ledger)`);
console.log(`  payable≤cap: ${payable.length}  ·  over-cap(defer): ${overCap.length}  ·  no-bazaar-price(agent probes): ${unknownPrice.length}`);
console.log(`  with bazaar callHint: ${agentSet.filter((r) => r.hasBazaar).length}/${agentSet.length}`);
console.log(`agent set: ${args.endpoints.length} (capped at --max=${MAX})  → ${outFile.replace(ROOT + "/", "")}`);
console.log(`est. worst-case spend if all pay: $${agentSet.reduce((a, r) => a + (r.priceUsd && r.priceUsd <= CAP ? r.priceUsd : 0), 0).toFixed(3)}`);
if (overCap.length) console.log(`  (${overCap.length} over-cap deferred — recorded to ledger)`);
